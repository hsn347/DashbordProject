-- ── user_roles ──────────────────────────────────────────────────
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "user_roles: self read"  ON public.user_roles;
DROP POLICY IF EXISTS "user_roles: admin full" ON public.user_roles;

CREATE POLICY "user_roles: self read"
  ON public.user_roles FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "user_roles: admin full"
  ON public.user_roles FOR ALL
  USING (public.is_admin());

-- ── profiles ────────────────────────────────────────────────────
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "profiles: self read"    ON public.profiles;
DROP POLICY IF EXISTS "profiles: self update"  ON public.profiles;
DROP POLICY IF EXISTS "profiles: admin full"   ON public.profiles;

CREATE POLICY "profiles: self read"
  ON public.profiles FOR SELECT
  USING (auth.uid() = id);

CREATE POLICY "profiles: self update"
  ON public.profiles FOR UPDATE
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

CREATE POLICY "profiles: admin full"
  ON public.profiles FOR ALL
  USING (public.is_admin());

-- ── Accounts ────────────────────────────────────────────────────
ALTER TABLE public."Accounts" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "accounts: owner select" ON public."Accounts";
DROP POLICY IF EXISTS "accounts: owner insert" ON public."Accounts";
DROP POLICY IF EXISTS "accounts: owner update" ON public."Accounts";
DROP POLICY IF EXISTS "accounts: owner delete" ON public."Accounts";

-- المستخدم يرى حساباته فقط (نستخدم user_id مباشرة بدلاً من Emulators)
CREATE POLICY "accounts: owner select"
  ON public."Accounts" FOR SELECT
  USING (auth.uid()::TEXT = user_id);

CREATE POLICY "accounts: owner insert"
  ON public."Accounts" FOR INSERT
  WITH CHECK (auth.uid()::TEXT = user_id);

CREATE POLICY "accounts: owner update"
  ON public."Accounts" FOR UPDATE
  USING (auth.uid()::TEXT = user_id);

CREATE POLICY "accounts: owner delete"
  ON public."Accounts" FOR DELETE
  USING (auth.uid()::TEXT = user_id);

-- ── admin_settings ──────────────────────────────────────────────
ALTER TABLE public.admin_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "settings: public read"  ON public.admin_settings;
DROP POLICY IF EXISTS "settings: admin write"  ON public.admin_settings;

-- الكل يقرأ الإعدادات
CREATE POLICY "settings: public read"
  ON public.admin_settings FOR SELECT
  USING (true);

