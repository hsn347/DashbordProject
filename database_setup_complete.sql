-- ────────────────────────────────────────────────────────────────
-- ① جدول user_roles  (نظام الأدوار: admin / user)
-- ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.user_roles (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE UNIQUE NOT NULL,
  role    TEXT NOT NULL DEFAULT 'user',
  CONSTRAINT valid_role CHECK (role IN ('user', 'admin'))
);

-- ────────────────────────────────────────────────────────────────
-- ② جدول profiles  (بيانات المستخدم الممتدة)
-- ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.profiles (
  id              UUID NOT NULL,
  username        TEXT NULL,
  full_name       TEXT NULL,
  updated_at      TIMESTAMP WITH TIME ZONE NULL DEFAULT now(),
  created_at      TIMESTAMP WITH TIME ZONE NULL DEFAULT now(),
  allowed_accounts NUMERIC NULL,
  "Is_COMP"       BOOLEAN NULL,
  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_id_fkey FOREIGN KEY (id)
    REFERENCES auth.users (id) ON DELETE CASCADE,
  CONSTRAINT username_length CHECK (char_length(username) >= 3)
);

-- فهارس profiles
CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_lower_idx
  ON public.profiles USING btree (lower(username))
  WHERE (username IS NOT NULL);

CREATE INDEX IF NOT EXISTS profiles_created_at_idx
  ON public.profiles USING btree (created_at);

-- Triggers لـ profiles
DROP TRIGGER IF EXISTS profiles_set_updated_at ON public.profiles;
CREATE TRIGGER profiles_set_updated_at
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS profiles_normalize_username ON public.profiles;
CREATE TRIGGER profiles_normalize_username
  BEFORE INSERT OR UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.normalize_username();

