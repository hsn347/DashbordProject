-- دالة is_admin: هل المستخدم الحالي أدمن؟
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_roles
    WHERE user_id = auth.uid()
      AND role = 'admin'
  );
$$;


-- دالة reindex_accounts_v2
-- توزع الحسابات المعتمدة على السيرفرات بالتسلسل
CREATE OR REPLACE FUNCTION public.reindex_accounts_v2()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_max_per_server   INT;
  v_server_count     INT;
  v_total_slots      INT;
  v_rec              RECORD;
  v_slot             INT := 0;
BEGIN
  -- اقرأ الإعدادات
  SELECT value::INT INTO v_max_per_server
  FROM public.admin_settings WHERE key = 'max_accounts_per_server';
  v_max_per_server := COALESCE(v_max_per_server, 50);

  SELECT value::INT INTO v_server_count
  FROM public.admin_settings WHERE key = 'server_count';
  v_server_count := COALESCE(v_server_count, 5);

  v_total_slots := v_max_per_server * v_server_count;

  -- أصفر index_server لكل الحسابات غير المعتمدة أولاً
  UPDATE public."Accounts"
  SET index_server = NULL
  WHERE "Is_OK" = false OR "Is_OK" IS NULL;

  -- وزّع الحسابات المعتمدة على السيرفرات بالترتيب
  FOR v_rec IN
    SELECT id
    FROM public."Accounts"
    WHERE "Is_OK" = true
    ORDER BY "Date_OK" ASC, id ASC
  LOOP
    IF v_slot < v_total_slots THEN
      UPDATE public."Accounts"
      SET index_server = ((v_slot / v_max_per_server) + 1)::TEXT
      WHERE id = v_rec.id;
      v_slot := v_slot + 1;
    ELSE
      -- تجاوز الطاقة: ألغِ الاعتماد
      UPDATE public."Accounts"
      SET "Is_OK" = false, index_server = NULL
      WHERE id = v_rec.id;
    END IF;
  END LOOP;
END;
$$;


-- دالة auto_approve_user_accounts
-- تعتمد تلقائياً أقدم N حساب للمستخدم بناءً على الكوتا
CREATE OR REPLACE FUNCTION public.auto_approve_user_accounts(p_user_id TEXT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_quota      INT;
  v_is_comp    BOOLEAN;
  v_approved   INT[];
  v_rejected   INT[];
BEGIN
  -- اجلب الكوتا وحالة المستخدم
  SELECT COALESCE(allowed_accounts, 0)::INT, COALESCE("Is_COMP", false)
  INTO v_quota, v_is_comp
  FROM public.profiles
  WHERE id = p_user_id::UUID;

  IF NOT FOUND THEN RETURN; END IF;

  -- إذا المستخدم غير مفعّل، ألغِ كل حساباته
  IF v_is_comp = false THEN
    UPDATE public."Accounts"
    SET "Is_OK" = false, index_server = NULL
    WHERE user_id = p_user_id;
    PERFORM public.reindex_accounts_v2();
    RETURN;
  END IF;

  -- اجمع IDs الحسابات مرتبة بالأقدم
  SELECT
    array_agg(id ORDER BY created_at ASC) FILTER (WHERE ordinality <= v_quota),
    array_agg(id ORDER BY created_at ASC) FILTER (WHERE ordinality >  v_quota)
  INTO v_approved, v_rejected
  FROM (
    SELECT id, created_at,
           row_number() OVER (ORDER BY created_at ASC) AS ordinality
    FROM public."Accounts"
    WHERE user_id = p_user_id
  ) sub;

  -- اعتمد الأقدم N
  IF v_approved IS NOT NULL AND array_length(v_approved, 1) > 0 THEN
    UPDATE public."Accounts"
    SET "Is_OK" = true
    WHERE id = ANY(v_approved);
  END IF;

  -- ألغِ الباقين
  IF v_rejected IS NOT NULL AND array_length(v_rejected, 1) > 0 THEN
    UPDATE public."Accounts"
    SET "Is_OK" = false, index_server = NULL
    WHERE id = ANY(v_rejected);
  END IF;

  -- أعد توزيع السيرفرات
  PERFORM public.reindex_accounts_v2();
END;
$$;


-- دالة auto_approve_all_users
-- تطبق auto_approve على جميع المستخدمين دفعةً واحدة
CREATE OR REPLACE FUNCTION public.auto_approve_all_users()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user RECORD;
BEGIN
  FOR v_user IN
    SELECT id::TEXT FROM public.profiles
  LOOP
    PERFORM public.auto_approve_user_accounts(v_user.id);
  END LOOP;
END;
$$;


-- دالة handle_new_user  (Trigger على auth.users)
-- تُنشئ profile تلقائياً عند تسجيل مستخدم جديد
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, username, full_name)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1)),
    COALESCE(NEW.raw_user_meta_data->>'full_name', '')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

-- ربط الـ Trigger بجدول auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


